const { chromium } = require('C:/Users/oblako/AppData/Local/npm-cache/_npx/e41f203b7505f1fb/node_modules/playwright');
const fs=require('fs');
(async()=>{
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
await page.goto('https://webdesign.kernjosh.com/',{waitUntil:'domcontentloaded',timeout:60000});
await page.waitForTimeout(4500);
const record=async(label)=>({label,url:page.url(),scrollY:await page.evaluate(()=>window.scrollY),process:await page.locator('[class*="process"]').evaluateAll(els=>els.filter(el=>['SECTION','OL','LI','BUTTON'].includes(el.tagName)).map(el=>{const s=getComputedStyle(el),r=el.getBoundingClientRect();return{tag:el.tagName,class:el.className,text:el.innerText,ariaLabel:el.getAttribute('aria-label'),role:el.getAttribute('role'),ariaHidden:el.getAttribute('aria-hidden'),box:[r.x,r.y,r.width,r.height],display:s.display,opacity:s.opacity,visibility:s.visibility,transform:s.transform}})),nav:await page.locator('.nav-pill').evaluateAll(els=>els.slice(0,6).map(el=>{const s=getComputedStyle(el),r=el.getBoundingClientRect();return{text:el.innerText,class:el.className,box:[r.x,r.y,r.width,r.height],background:s.backgroundColor,borderRadius:s.borderRadius,opacity:s.opacity,display:s.display,visibility:s.visibility}}))});
const states=[await record('closed')];
await page.getByRole('button',{name:'Process',exact:true}).hover();
await page.waitForTimeout(200);
await page.screenshot({path:__dirname+'/02-pill-hover.png'});
await page.getByRole('button',{name:'Process',exact:true}).click();
await page.waitForTimeout(120);
await page.screenshot({path:__dirname+'/03-opening.png'});
await page.waitForTimeout(1000);
await page.screenshot({path:__dirname+'/04-open.png'});
states.push(await record('open'));
await page.mouse.move(1300,700);
await page.mouse.wheel(0,850);
await page.waitForTimeout(1200);
await page.screenshot({path:__dirname+'/05-after-scroll.png'});
states.push(await record('after-scroll'));
await page.locator('.process-step').nth(2).click();
await page.waitForTimeout(700);
await page.screenshot({path:__dirname+'/06-third-step.png'});
states.push(await record('third-step'));
await page.locator('.process-step').nth(4).click();
await page.waitForTimeout(700);
await page.screenshot({path:__dirname+'/07-fifth-step.png'});
states.push(await record('fifth-step'));
await page.locator('.nav-pill--back').click();
await page.waitForTimeout(1300);
await page.screenshot({path:__dirname+'/08-back.png'});
states.push(await record('back'));
fs.writeFileSync(__dirname+'/states.json',JSON.stringify(states,null,2));
console.log(JSON.stringify(states.map(s=>({label:s.label,url:s.url,scrollY:s.scrollY,active:s.process.filter(p=>p.class.includes("is-active")),nav:s.nav})),null,2));
await browser.close();
})();

